"""Build the installable Sesong web app from the prototype page.

Usage: python3 tools/build.py [path/to/sesong-source.html]

Reads the prototype page (written as an artifact body, without <html>/<head>),
wraps it in a full document with home-screen metadata, and writes
sesong/index.html, sesong/manifest.webmanifest, sesong/sw.js and app icons.
"""
import hashlib
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP = os.path.join(ROOT, "sesong")
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "tools", "sesong-source.html")

BG = "#EDE3D2"
INK = "#2B2924"
TERRA = "#D8735C"
SAGE = "#93AC86"

HEAD = """<!doctype html>
<html lang="nb">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="theme-color" content="{bg}">
<meta name="description" content="Hva er i sesong i Norge nå, hvor du får tak i det, oppskrifter og vinforslag.">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Sesong">
<meta name="apple-mobile-web-app-status-bar-style" content="default">
<link rel="manifest" href="manifest.webmanifest">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<link rel="icon" type="image/png" sizes="192x192" href="icons/icon-192.png">
<style>
:root {{ color-scheme: light; padding-top: env(safe-area-inset-top, 0px); padding-bottom: env(safe-area-inset-bottom, 0px); }}
body {{ margin: 0; font: 14px/1.4 system-ui, sans-serif; overscroll-behavior-y: none; }}
img {{ max-width: 100%; }}
[hidden] {{ display: none !important; }}
</style>
"""

SW_REGISTER = """
<script>
if ("serviceWorker" in navigator) {
  window.addEventListener("load", () => { navigator.serviceWorker.register("sw.js").catch(() => {}); });
}
</script>
"""


def build_index():
    src = open(SRC, encoding="utf-8").read()
    # Everything up to the end of the first <style> block belongs in <head>
    cut = src.index("</style>") + len("</style>")
    head_part, body_part = src[:cut], src[cut:]
    head_part = head_part.replace('<meta name="claude:viewport-fit-sides" content="cover">\n', "")
    html = HEAD.format(bg=BG) + head_part + "\n</head>\n<body>\n" + body_part.strip() + "\n" + SW_REGISTER + "</body>\n</html>\n"
    open(os.path.join(APP, "index.html"), "w", encoding="utf-8").write(html)
    return html


def build_manifest():
    open(os.path.join(APP, "manifest.webmanifest"), "w", encoding="utf-8").write(f"""{{
  "name": "Sesong",
  "short_name": "Sesong",
  "description": "Hva er i sesong i Norge nå, hvor du får tak i det, oppskrifter og vinforslag.",
  "lang": "nb",
  "start_url": "./",
  "scope": "./",
  "display": "standalone",
  "background_color": "{BG}",
  "theme_color": "{BG}",
  "icons": [
    {{ "src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png" }},
    {{ "src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png" }},
    {{ "src": "icons/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable" }}
  ]
}}
""")


def build_sw(html):
    imgs = sorted(f for f in os.listdir(os.path.join(APP, "img")) if f.endswith(".webp"))
    # Version changes whenever the page or the photo set changes, so phones pick up updates
    version = hashlib.sha1((html + "|".join(imgs)).encode()).hexdigest()[:10]
    files = ["./", "index.html", "manifest.webmanifest", "icons/apple-touch-icon.png", "icons/icon-192.png"] + [f"img/{f}" for f in imgs]
    file_list = ",\n  ".join(f'"{f}"' for f in files)
    open(os.path.join(APP, "sw.js"), "w", encoding="utf-8").write(f"""// Offline cache for Sesong. Generated by tools/build.py; do not edit by hand.
const CACHE = "sesong-{version}";
const FILES = [
  {file_list}
];

self.addEventListener("install", e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
}});

self.addEventListener("activate", e => {{
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
}});

// Page: network first so updates show up, cache when offline. Everything else: cache first.
self.addEventListener("fetch", e => {{
  const req = e.request;
  if (req.method !== "GET") return;
  if (req.mode === "navigate") {{
    e.respondWith(fetch(req).then(res => {{
      const copy = res.clone(); caches.open(CACHE).then(c => c.put("index.html", copy)); return res;
    }}).catch(() => caches.match("index.html")));
    return;
  }}
  e.respondWith(caches.match(req).then(hit => hit || fetch(req).then(res => {{
    if (res.ok && new URL(req.url).origin === location.origin) {{ const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }}
    return res;
  }})));
}});
""")


def draw_icon(size, safe=1.0):
    """Cream tile with a terracotta brush stroke and a lowercase italic 's'."""
    s = size * 4  # draw large, then downscale for smooth edges
    img = Image.new("RGB", (s, s), BG)
    d = ImageDraw.Draw(img)
    pad = s * (1 - safe) / 2
    inner = s - 2 * pad
    pts = [(0.20, 0.34), (0.78, 0.28), (0.24, 0.52), (0.80, 0.48), (0.26, 0.70), (0.76, 0.68)]
    pts = [(pad + x * inner, pad + y * inner) for x, y in pts]
    w = int(inner * 0.17)
    d.line(pts, fill=TERRA, width=w, joint="curve")
    for x, y in (pts[0], pts[-1]):
        d.ellipse([x - w / 2, y - w / 2, x + w / 2, y + w / 2], fill=TERRA)
    d.ellipse([pad + inner * 0.70, pad + inner * 0.16, pad + inner * 0.84, pad + inner * 0.30], fill=SAGE)
    font_path = "/usr/share/fonts/opentype/inter/InterDisplay-LightItalic.otf"
    font = ImageFont.truetype(font_path, int(inner * 0.62)) if os.path.exists(font_path) else ImageFont.load_default()
    d.text((s / 2, s / 2 + inner * 0.02), "s", font=font, fill=INK, anchor="mm")
    return img.resize((size, size), Image.LANCZOS)


def build_icons():
    out = os.path.join(APP, "icons")
    os.makedirs(out, exist_ok=True)
    draw_icon(180).save(os.path.join(out, "apple-touch-icon.png"))
    draw_icon(192).save(os.path.join(out, "icon-192.png"))
    draw_icon(512).save(os.path.join(out, "icon-512.png"))
    draw_icon(512, safe=0.72).save(os.path.join(out, "icon-maskable-512.png"))


if __name__ == "__main__":
    build_icons()
    html = build_index()
    build_manifest()
    build_sw(html)
    print("Built", APP)
